#!/usr/bin/env python3
"""Generate dev/Forte_Dev/Suites/ApiList.lua: every `C_Namespace.Function` and every catalog global
function the SHIPPED addon (addon/**/*.lua, tests and Data excluded) references, for the Forte_Dev
API-presence suite (it asks the live client whether each one exists).

Reuses scripts/api_lint.py's scanner: its `REF` regex, its catalog files (`CATALOGS`), the same
comment stripping (`line.split("--")[0]`, `-- api-lint: ok` lines skipped) and the same file selection
(`/tests/` and `/Data/` out).

Two lists, by a static guard heuristic:
  hard  referenced somewhere WITHOUT a guard -> the client must have it; a miss FAILS the suite.
  soft  every reference sits on a guard line (if / and / or / not / type( / pcall / ~= nil) or within
        6 lines after a guard line that names it -> the code tolerates its absence; a miss is reported
        in the detail only.
Globals = catalog functions with no namespace (`kind: function`, symbol without `.`/`:`) the addon calls,
plus NON_CATALOG (Lua/FrameXML globals the catalog does not declare) when the addon calls them.

    python3 dev/gen_api_list.py           write the file
    python3 dev/gen_api_list.py --check   exit 1 when the committed file is stale (no write)

Deterministic (no timestamp), so re-running leaves no git churn.
"""
import glob, importlib.util, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(HERE, "Forte_Dev", "Suites", "ApiList.lua")

_spec = importlib.util.spec_from_file_location("api_lint", os.path.join(ROOT, "scripts", "api_lint.py"))
api_lint = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(api_lint)

NON_CATALOG = ["CreateFont", "CreateFrame", "debugstack", "geterrorhandler", "hooksecurefunc", "seterrorhandler",
               "strsplit", "strtrim", "tostringall", "wipe"]
GUARD = re.compile(r"\b(?:if|and|or|not|type|pcall|xpcall)\b|~=\s*nil|==\s*nil")
CALL = re.compile(r"(?<![\w.:])([A-Za-z_]\w*)\s*\(")
GCALL = re.compile(r"\b_G\.([A-Za-z_]\w*)")


def global_functions():
    names = set()
    for path in api_lint.CATALOGS:
        with open(path, errors="replace") as fh:
            doc = json.load(fh)
        for rec in doc.get("declarations", []):
            sym = rec.get("symbol") or ""
            if rec.get("kind") == "function" and sym and "." not in sym and ":" not in sym:
                names.add(sym)
    return names


def shipped_files():
    files = glob.glob(os.path.join(ROOT, "addon", "**", "*.lua"), recursive=True)
    return sorted(f for f in files if "/tests/" not in f and "/Data/" not in f)


def scan():
    gfuncs = global_functions() | set(NON_CATALOG)
    refs = {}      # symbol -> [guarded?, ...]
    files = shipped_files()
    for f in files:
        codes = []
        for line in open(f, errors="replace"):
            codes.append("" if "api-lint: ok" in line else line.split("--", 1)[0])
        for n, code in enumerate(codes):
            found = [f"{ns}.{fn}" for ns, fn in api_lint.REF.findall(code)]
            found += [m for m in CALL.findall(code) if m in gfuncs]
            found += [m for m in GCALL.findall(code) if m in gfuncs]
            for sym in found:
                name = sym.split(".")[0]
                guarded = bool(GUARD.search(code))
                if not guarded:
                    for prev in codes[max(0, n - 6):n]:
                        if (sym in prev or name in prev) and GUARD.search(prev):
                            guarded = True
                            break
                refs.setdefault(sym, []).append(guarded)
    return files, refs


def lua_list(items):
    return "{\n" + "".join(f'        "{s}",\n' for s in items) + "    }"


def render():
    files, refs = scan()
    hard = sorted(s for s, g in refs.items() if not all(g))
    soft = sorted(s for s, g in refs.items() if all(g))
    return (
        "-- Forte_Dev/Suites/ApiList.lua\n"
        "-- GENERATED by dev/gen_api_list.py from addon/**/*.lua -- do not edit by hand; re-run the script.\n"
        "-- hard = referenced unguarded (a miss fails the API-presence suite); soft = every reference is\n"
        "-- guarded (a miss is reported only). Scanner: scripts/api_lint.py (REF regex, catalogs, file filter).\n"
        "\n"
        "ForteXorcist = ForteXorcist or {}\n"
        "local FX = ForteXorcist\n"
        "\n"
        "FX.Dev.ApiList = {\n"
        f"    files = {len(files)},\n"
        f"    hard = {lua_list(hard)},\n"
        f"    soft = {lua_list(soft)},\n"
        "}\n"
    )


def main(argv):
    text = render()
    if "--check" in argv:
        current = open(OUT).read() if os.path.exists(OUT) else ""
        if current != text:
            print(f"[gen_api_list] STALE: {os.path.relpath(OUT, ROOT)} differs from the scan; re-run without --check")
            return 1
        print("[gen_api_list] up to date")
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", newline="\n") as fh:
        fh.write(text)
    hard = text.split("hard = {")[1].split("},")[0].count('"') // 2
    soft = text.split("soft = {")[1].split("}")[0].count('"') // 2
    print(f"[gen_api_list] wrote {os.path.relpath(OUT, ROOT)}: {hard} hard, {soft} soft")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
