-- addon/Forte_Hunter/tests/test_swing_sniper.lua
-- Sniper Shot (a 4 s cast, docs/research/live-hunter-2026-11-09.md §4.2) in
-- the swing bar's two cast-name sets:
--
-- 1. Core/Tools.lua SHOT_CAST_SET (the interlock machine): a Sniper Shot
--    SENT opens the interlock with the DATA length (4.0 s) when no live read
--    exists, the live reader / client castTime still outrank the data, and
--    SUCCEEDED / INTERRUPTED end it -- exactly the Aimed Shot shape.
-- 2. UI/Swing.lua CLIP_SHOT_NAMES (the IDLE clip mark): the longest KNOWN
--    cast-time shot sets the mark. Sniper Shot's data row ships for every
--    Hunter, so it counts ONLY when the player knows the spell (a Hunter
--    without it keeps the 2.0 s Aimed Shot mark -- the data walk is gated
--    on Compat.IsPlayerSpell for that name alone).
--
-- Ids ride the GENERATED ByName key space (spell ids are never hand-typed,
-- AGENTS.md). Compat.IsPlayerSpell / C_Spell.GetSpellInfo are module-table
-- fields the AutoRestore does not cover: every injection is paired with its
-- restore inside the leg (the test_swing_casttime.lua law).

local FX = ForteXorcist
local Tools = FX.Hunter.Tools
local Swing = FX.Hunter.Swing

local function near(actual, expected)
    return assertTrue(math.abs(actual - expected) <= 1e-3,
        tostring(actual) .. " ~= " .. tostring(expected))
end

local SNIPER_ID = FX.Data and FX.Data.HunterByName and FX.Data.HunterByName["Sniper Shot"]
local AIMED_ID = FX.Data and FX.Data.HunterByName and FX.Data.HunterByName["Aimed Shot"]
assertNotNil(SNIPER_ID, "the generated ByName key resolves Sniper Shot")
assertNotNil(AIMED_ID, "the generated ByName key resolves Aimed Shot")
assertEquals(4000, FX.Data.Hunter[SNIPER_ID].castMs,
    "the shipped Sniper Shot row is the 4 s cast the report measured")
assertEquals(2000, FX.Data.Hunter[AIMED_ID].castMs)

--- A permissive-gate tracker (test_swing2.lua's shape).
local function v2Tracker(clock, extra)
    local opts = {
        now = function() return clock[1] end,
        speedReader = function() return nil end,
        rangedType = 2,
        targetReader = function() return true end,
        deadReader = function() return false end,
        attackReader = function() return true end,
        speedSampler = function() return nil end,
        rangeReader = function() return nil end,
        castLenReader = function() return nil end,
    }
    for k, v in pairs(extra or {}) do opts[k] = v end
    local t = FX.Hunter.NewSwingTracker(opts)
    t.shooting = true
    return t
end

-- ============================================== 1. the interlock machine ==

test("sniper: a SENT opens the interlock on the DATA 4.0 s; SUCCEEDED ends it",
function()
    local clock = { 1000 }
    local t = v2Tracker(clock)
    t:OnSwingStart(3.0, 2)
    t:OnShotCast("SENT", "Sniper Shot", nil, "GS")
    local left, len = t:CastRemaining(1000.2)
    assertNotNil(left, "Sniper Shot opens the interlock like Aimed Shot")
    near(len, 4.0)
    -- A START for the same cast is idempotent (no double length).
    t:OnShotCast("START", "Sniper Shot", nil, "GS")
    local _, len2 = t:CastRemaining(1000.3)
    near(len2, 4.0)
    t:OnShotCast("SUCCEEDED", "Sniper Shot", nil, "GS")
    assertNil(t:CastRemaining(1001))
end)

test("sniper: the live reader beats the data length; INTERRUPTED ends the cast",
function()
    local clock = { 2000 }
    local t = v2Tracker(clock, { castLenReader = function() return 3.2 end })
    t:OnSwingStart(3.0, 2)
    t:OnShotCast("SENT", "Sniper Shot", SNIPER_ID, "GL")
    local _, len = t:CastRemaining(2000.1)
    near(len, 3.2)
    t:OnShotCast("INTERRUPTED", "Sniper Shot", SNIPER_ID, "GL")
    assertNil(t:CastRemaining(2000.5))
end)

test("sniper: a foreign GUID's SUCCEEDED does not end the live Sniper cast",
function()
    local clock = { 3000 }
    local t = v2Tracker(clock)
    t:OnShotCast("SENT", "Sniper Shot", nil, "G-MINE")
    assertNotNil(t:CastRemaining(3000.1))
    t:OnShotCast("SUCCEEDED", "Sniper Shot", nil, "G-OTHER")
    assertNotNil(t:CastRemaining(3000.2), "the seal law: another cast's end is not ours")
    t:OnShotCast("SUCCEEDED", "Sniper Shot", nil, "G-MINE")
    assertNil(t:CastRemaining(3000.3))
end)

test("sniper: spells outside the set still never open the interlock",
function()
    local clock = { 4000 }
    local t = v2Tracker(clock)
    t:OnShotCast("SENT", "Kill Shot", nil, "GK")
    assertNil(t:CastRemaining(4000.1))
    t:OnShotCast("SENT", "Arcane Shot", nil, "GA")
    assertNil(t:CastRemaining(4000.1))
end)

-- ================================================== 2. the idle clip mark ==

local REAL_ISP = FX.Compat.IsPlayerSpell
local REAL_GSI = _G.C_Spell and _G.C_Spell.GetSpellInfo
assertNotNil(REAL_GSI, "the sim resolves C_Spell.GetSpellInfo")
local injectedGSI = false

local function useKnown(fn)
    FX.Compat.IsPlayerSpell = fn
    Swing:InvalidateClipCastLength()
end
--- The client leg answers the two rows' data lengths so the live read can
--- not drift from the data this test plays against (ms, the catalog shape).
local function useClientLengths()
    _G.C_Spell.GetSpellInfo = function(id, ...)
        if id == SNIPER_ID then return { castTime = 4000 } end
        if id == AIMED_ID then return { castTime = 2000 } end
        return REAL_GSI(id, ...)
    end
    injectedGSI = true
    Swing:InvalidateClipCastLength()
end
local function restoreAll()
    FX.Compat.IsPlayerSpell = REAL_ISP
    if injectedGSI then
        _G.C_Spell.GetSpellInfo = REAL_GSI
        injectedGSI = false
    end
    Swing:InvalidateClipCastLength()
end

test("clip mark: a Hunter who does NOT know Sniper Shot keeps the 2.0 s Aimed mark",
function()
    local ok, err = pcall(function()
        useClientLengths()
        useKnown(function() return false end)
        near(Swing:ClipCastSeconds(), 2.0)
        -- Knowing every spell BUT Sniper Shot is the same answer: the gate
        -- is per name, Aimed Shot's own leg is untouched.
        useKnown(function(id) return id ~= SNIPER_ID end)
        near(Swing:ClipCastSeconds(), 2.0)
    end)
    restoreAll()
    if not ok then error(err, 0) end
end)

test("clip mark: a Hunter who knows Sniper Shot gets the 4.0 s mark",
function()
    local ok, err = pcall(function()
        useClientLengths()
        useKnown(function(id) return id == SNIPER_ID end)
        near(Swing:ClipCastSeconds(), 4.0)
    end)
    restoreAll()
    if not ok then error(err, 0) end
end)

test("clip mark: a raising / secret known-read is 'not known' (2.0 s), never a raise",
function()
    local ok, err = pcall(function()
        useClientLengths()
        useKnown(function() error("FXTEST-ISP-RAISE", 0) end)
        local ok2, sec = pcall(Swing.ClipCastSeconds, Swing)
        assertTrue(ok2, "the known read's raise is swallowed")
        near(sec, 2.0)
    end)
    restoreAll()
    if not ok then error(err, 0) end
end)
