-- addon/Forte_Hunter/tests/test_swing_casttime.lua
-- Two laws of the swing bar, fail-first:
--
-- 1. The clip mark's CAST-LENGTH SOURCE (UI/Swing.lua's ClipCastSeconds):
--    the CLIENT's current cast time of the shot the shipped data names
--    the interlock set's longest cast-time shot outranks the data row.
--    The read is the tracker's own seam -- C_Spell.GetSpellInfo(id)
--    .castTime in MILLISECONDS through Tools.ResolveCastLength (one pcall
--    around lookup + field read, PlainOrNil on the number: only a plain
--    positive number counts, the M3 law). Measured live on uiforever
--    2026-11-04: Aimed Shot rides 3.0 s on the client while the generated
--    row says 2000 ms, so a data-only idle clip mark understates by a
--    second on such a client. Legs:
--      (a) a stubbed client 3000 ms widens the IDLE safe-mode band to
--          3.0 x scale -- not the data's 2.0 x scale;
--      (b) a SECRET read falls back to the data 2.0 s (the sentinel
--          idiom, test_probe.lua / test_compat.lua: the sim mints no real
--          secret, the seam patches _G.issecretvalue);
--      (c) a RAISING read falls back the same way;
--      (d) the NO-PER-FRAME-API cadence: one whole cycle costs at most
--          ONE seam read of the id, the passes inside it cost none, the
--          next cycle costs the one re-read (the per-cycle cache,
--          UI/Swing.lua's _ClientClipSeconds -- the bar listens to
--          neither SPELLS_CHANGED nor a haste event, the cycle boundary
--          is this file's re-read point).
-- 2. SetFillEngineMode's fill SURVIVES a rebuild (UI/Swing.lua): a switch
--    BEFORE Init defers the build (no crash; Init's _BuildFill leg reads
--    the recorded mode), and a switch against a torn-down bar whose
--    rebuild RAISES keeps the fill that was drawing -- the pre-guard
--    order nil'd `fill` first and left a fill-less bar for Update to
--    index (the fossil: test_swing_palette.lua's memo-drop). After both,
--    Update draws.
--
-- The Aimed Shot id rides the GENERATED ByName key space (spell ids are
-- never hand-typed, AGENTS.md); C_Spell.GetSpellInfo / _G.issecretvalue /
-- the Swing._BuildFill seam are module/table fields the AutoRestore does
-- not cover, so every injection is paired with its restore INSIDE the
-- leg (the test_swing_modes.lua law), asserts under pcall with the
-- restore-before-rethrow shape.

local FX = ForteXorcist
local Tools = FX.Hunter.Tools
local Swing = FX.Hunter.Swing
local S = FX.Hunter.SwingSkin

local function nearpx(actual, expected)
    return assertTrue(math.abs(actual - expected) <= 0.5)
end

local AIMED_ID = FX.Data and FX.Data.HunterByName
    and FX.Data.HunterByName["Aimed Shot"]
assertNotNil(AIMED_ID, "the generated ByName key resolves Aimed Shot")
local AIMED_ROW = FX.Data.Hunter[AIMED_ID]
assertNotNil(AIMED_ROW)
assertNotNil(AIMED_ROW.castMs, "the shipped row carries a cast time")
assertTrue(math.abs(AIMED_ROW.castMs / 1000 - 2.0) < 1e-3,
    "the data row is the 2.0 s the client leg plays against: "
    .. tostring(AIMED_ROW.castMs))

--- A permissive-gate tracker (test_swing2.lua's shape).
local function v2Tracker(clock, extra)
    local opts = {
        now = function() return clock[1] end,
        speedReader = function() return nil end,
        rangedType = 2,
        targetReader = function() return true end,
        deadReader = function() return false end,
        attackReader = function() return true end,
        speedSampler = function() return nil end,
        rangeReader = function() return nil end,
        castLenReader = function() return nil end,
    }
    for k, v in pairs(extra or {}) do opts[k] = v end
    local t = FX.Hunter.NewSwingTracker(opts)
    t.shooting = true
    return t
end

local W = 200
Swing:SetFillEngineMode("lua")
Swing:Init()
assertNotNil(Swing.anchor)

-- The C_Spell.GetSpellInfo seam: the legs ride a wrapper that answers the
-- Aimed Shot row and passes every other id through (the row shape is the
-- catalog's SpellInfo: the `.castTime` field, in MS -- the reading
-- Tools.ResolveCastLength implements). A field write on the C_Spell
-- table: paired restore, the module-field law.
local REAL_GSI = _G.C_Spell and _G.C_Spell.GetSpellInfo
assertNotNil(REAL_GSI, "the sim resolves C_Spell.GetSpellInfo")
local injectedGSI = false
local REAL_ISS = _G.issecretvalue
local function useGSI(leg)
    _G.C_Spell.GetSpellInfo = leg
    injectedGSI = true
    Swing:InvalidateClipCastLength()      -- the memo drop forces a re-read
end
local function restoreAll()
    if injectedGSI then
        _G.C_Spell.GetSpellInfo = REAL_GSI
        injectedGSI = false
    end
    _G.issecretvalue = REAL_ISS
    Swing:SetBarMode("safe")
    Swing:SetShowAimWindow(true)      -- the shipped marker defaults (the
    Swing:SetShowClipRegion(true)     -- mode files capture them at load)
    Swing:SetShowWeaveLine(false)
    Swing:SetFillEngineMode("lua")
    Swing:SetTracker(Tools.Swing)
    Swing:RenderIdle()
    Swing:InvalidateClipCastLength()
end

--- The bar in the idle clip-mark posture: safe mode, the band on, one
--- 4.0 s cycle (scale 50) at `clock0`; returns the tracker + clock.
local function clipCycle(clock0)
    Swing:SetBarMode("safe")
    Swing:SetShowAimWindow(false)
    Swing:SetShowClipRegion(true)
    Swing:SetShowWeaveLine(false)
    local clock = { clock0 }
    local t = v2Tracker(clock, { baseSpeed = 4.0 })
    Swing:SetTracker(t)
    Swing:RenderIdle()
    t:OnSwingStart(4.0, 2)                -- aimLen 0.5, scale W/4 = 50
    return clock, t
end

-- ============================================ 1. the client length wins ==

test("clip mark: a stubbed 3000 ms client cast time widens the idle safe band to 3.0 x scale",
function()
    local ok, err = pcall(function()
        useGSI(function(id, ...)
            if id == AIMED_ID then return { castTime = 3000 } end
            return REAL_GSI(id, ...)
        end)
        local clock = clipCycle(21000)
        Swing:Update(clock[1])
        -- The seam reads the client, not the row.
        local sec = Swing:ClipCastSeconds()
        assertNotNil(sec)
        assertTrue(math.abs(sec - 3.0) < 1e-3,
            "the seam rides the client: " .. tostring(sec))
        local band = Swing.clipBand
        assertTrue(band:IsShown(), "the idle safe band is on")
        nearpx(band:GetWidth(), 3.0 * (W / 4.0))            -- 150 px
        assertTrue(math.abs(band:GetWidth() - 2.0 * (W / 4.0)) > 0.5,
            "NOT the data length: " .. tostring(band:GetWidth()))
        Swing:RenderIdle()
    end)
    restoreAll()
    if not ok then error(err, 0) end
end)

test("clip mark: a SECRET client read falls back to the data 2.0 s",
function()
    local ok, err = pcall(function()
        local SENT = "FXTEST-SECRET-CASTMS"
        _G.issecretvalue = function(v) return v == SENT end
        local ok2, err2 = pcall(function()
            useGSI(function(id, ...)
                if id == AIMED_ID then return { castTime = SENT } end
                return REAL_GSI(id, ...)
            end)
            local clock = clipCycle(21500)
            Swing:Update(clock[1])
            local sec = Swing:ClipCastSeconds()
            assertNotNil(sec)
            assertTrue(math.abs(sec - 2.0) < 1e-3,
                "the data fallback: " .. tostring(sec))
            assertTrue(Swing.clipBand:IsShown())
            nearpx(Swing.clipBand:GetWidth(), 2.0 * (W / 4.0))   -- 100 px
            Swing:RenderIdle()
        end)
        _G.issecretvalue = REAL_ISS
        if not ok2 then error(err2, 0) end
    end)
    restoreAll()
    if not ok then error(err, 0) end
end)

test("clip mark: a RAISING client read falls back to the data 2.0 s",
function()
    local ok, err = pcall(function()
        useGSI(function(id, ...)
            if id == AIMED_ID then error("FXTEST-GSI-RAISE", 0) end
            return REAL_GSI(id, ...)
        end)
        local clock = clipCycle(21800)
        local ok2 = pcall(Swing.Update, Swing, clock[1])
        assertTrue(ok2, "the seam's raise is swallowed by the read, not the pass")
        local sec = Swing:ClipCastSeconds()
        assertTrue(math.abs(sec - 2.0) < 1e-3,
            "the data fallback: " .. tostring(sec))
        assertTrue(Swing.clipBand:IsShown())
        nearpx(Swing.clipBand:GetWidth(), 2.0 * (W / 4.0))       -- 100 px
        Swing:RenderIdle()
    end)
    restoreAll()
    if not ok then error(err, 0) end
end)

test("clip mark: the live read costs ONE seam read per cycle, none per frame",
function()
    local ok, err = pcall(function()
        local reads = 0
        useGSI(function(id, ...)
            if id == AIMED_ID then
                reads = reads + 1
                return { castTime = 3000 }
            end
            return REAL_GSI(id, ...)
        end)
        local clock, t = clipCycle(22000)
        -- Cycle one: the first pass reads the cycle, the rest of the
        -- 10 Hz + 0.05 s grid rides the cache.
        Swing:Update(clock[1])
        assertEquals(1, reads, "the cycle's first pass reads once")
        for i = 1, 20 do
            clock[1] = 22000 + i * 0.05
            assertTrue(Swing:Update(clock[1]))
        end
        assertEquals(1, reads, "no pass inside the cycle re-reads: " .. reads)
        -- Cycle two (the cycle boundary is the re-read point, the bar
        -- carries no SPELLS_CHANGED / haste registration).
        clock[1] = 22004.0
        t:OnSwingStart(4.0, 2)
        Swing:Update(clock[1])
        assertEquals(2, reads, "the next cycle costs the one re-read")
        for i = 1, 20 do
            clock[1] = 22004.0 + i * 0.05
            assertTrue(Swing:Update(clock[1]))
        end
        assertEquals(2, reads, "cycle two runs on the cache: " .. reads)
        Swing:RenderIdle()
    end)
    restoreAll()
    if not ok then error(err, 0) end
end)

-- ======================================= 2. SetFillEngineMode keeps a fill ==

test("fill rebuild: a mode switch BEFORE Init defers it (no crash), the fill arrives and draws",
function()
    local ok, err = pcall(function()
        -- The pre-Init state of the module (Init is idempotent, so the
        -- suite's shared singleton cannot un-Init -- the state is
        -- emulated and every field the switch touches is restored):
        -- the bar has no frame, no fill.
        local savedAnchor, savedFill = Swing.anchor, Swing.fill
        Swing.anchor, Swing.fill, Swing._engineFill = nil, nil, nil
        Swing._fillMode = "lua"
        local ok2 = pcall(Swing.SetFillEngineMode, Swing, "engine")
        assertTrue(ok2, "the switch on a not-yet-built bar does not raise")
        assertNil(Swing.fill, "the pre-Init switch builds no fill (deferred)")
        assertEquals("engine", Swing._fillMode, "the mode is recorded for Init")
        -- Init's fill leg, verbatim (UI/Swing.lua Init: `_BuildFill(f)`
        -- reads _fillMode through _FillEngineWanted).
        Swing.anchor = savedAnchor
        Swing:_BuildFill(Swing.anchor)
        assertNotNil(Swing.fill, "the deferred build arrives")
        assertTrue(Swing:UsesEngineFill(), "built on the deferred mode")
        -- Then Update draws it: a running cycle reaches the fill.
        local clock = { 23000 }
        local t = v2Tracker(clock, { baseSpeed = 2.0 })
        Swing:SetTracker(t)
        Swing:RenderIdle()
        t:OnSwingStart(2.0, 2)
        assertTrue(Swing:Update(clock[1]))
        assertNotNil(Swing._fillIntent, "Update drew the fill")
        clock[1] = 23001.0
        assertTrue(Swing:Update(clock[1]))
        assertNotNil(Swing.fill:GetWidth())
        Swing:RenderIdle()
    end)
    restoreAll()
    if not ok then error(err, 0) end
end)

test("fill rebuild: a mode switch after a teardown, and a raising rebuild, keep the drawing fill; Update draws",
function()
    local ok, err = pcall(function()
        -- The class's own teardown for this bar (UI/Swing.lua's
        -- OnClassChanged: the frames come down), then a mode switch
        -- against the torn-down bar: the fill that drew must survive.
        Swing:OnClassChanged("DRUID")
        assertNotNil(Swing.fill, "the teardown keeps the fill object")
        local ok2 = pcall(Swing.SetFillEngineMode, Swing, "engine")
        assertTrue(ok2, "the plain switch on the torn-down bar does not raise")
        assertNotNil(Swing.fill, "the switch on the torn-down bar kept a fill")
        assertTrue(Swing:UsesEngineFill(), "it is the widget the switch built")
        local widget = Swing.fill
        -- The torn-down parent's raise at the seam the switch drives
        -- (the sim's hidden-frame CreateTexture returning nil feeds
        -- fill:SetTexture a nil -- the raise is emulated at the seam
        -- deterministically). The guard must swallow it, keep the fill,
        -- and keep the fill's own path.
        local realBuild = Swing._BuildFill
        Swing._BuildFill = function() error("FXTEST-TORN-DOWN", 0) end
        local ok3 = pcall(Swing.SetFillEngineMode, Swing, "lua")
        Swing._BuildFill = realBuild
        assertTrue(ok3, "the guarded switch swallows the torn-down raise")
        assertNotNil(Swing.fill, "the raise kept a fill (never nil)")
        assertTrue(Swing.fill == widget, "the fill that drew keeps drawing")
        assertTrue(Swing:UsesEngineFill(), "its path survived the failed switch")
        -- K9 m4 (docs/reviews/code-review-9.md MINOR 4): the MEMO rides
        -- the restore. Pre-fix it stayed on the requested "lua" while
        -- the engine widget kept drawing -- the memo claimed a mode the
        -- bar does not run, and a repeat call to "lua" was a memo no-op:
        -- no retry.
        assertEquals("engine", Swing._fillMode,
            "the memo names the fill that DRAWS, not the failed switch")
        -- The bar comes back (OnClassChanged is idempotent through Init)
        -- and Update DRAWS on it.
        Swing:OnClassChanged("HUNTER")
        local clock = { 23500 }
        local t = v2Tracker(clock, { baseSpeed = 2.0 })
        Swing:SetTracker(t)
        Swing:RenderIdle()
        t:OnSwingStart(2.0, 2)
        assertTrue(Swing:Update(clock[1]))
        assertNotNil(Swing._fillIntent, "Update drew the fill")
        clock[1] = 23501.0
        assertTrue(Swing:Update(clock[1]))
        assertNotNil(Swing._fillIntent)
        Swing:RenderIdle()
        -- K9 m4: the RETRY lands. The bar is whole and the memo names
        -- the drawing engine path, so the switch to "lua" is a real
        -- call, not the memo echo it was pre-fix (pre-fix: the memo read
        -- "lua", the call no-oped, and the engine widget stayed on the
        -- bar -- the assert below fails on it). It rebuilds.
        Swing:SetFillEngineMode("lua")
        assertEquals("lua", Swing._fillMode, "the retry spoke")
        assertFalse(Swing:UsesEngineFill(), "the retry rebuilt on the requested mode")
        -- Back to the shipped v2 posture: the mode already reads "lua",
        -- the memo-drop idiom (test_swing_palette.lua's restoreAll)
        -- forces the real rebuild on the visible-then-idle bar.
        Swing._fillMode = nil
        Swing:SetFillEngineMode("lua")
        assertNotNil(Swing.fill, "the shipped posture is restored with a fill")
        assertFalse(Swing:UsesEngineFill())
    end)
    restoreAll()
    if not ok then error(err, 0) end
end)
